export const PipelineScrub: React.FC = () => {
  const [activeStep, setActiveStep] = useState<number>(1);
  const [autoWalk, setAutoWalk] = useState<boolean>(false);

  useEffect(() => {
    if (!autoWalk) return;
    const timer = window.setInterval(() => {
      setActiveStep((prev) => (prev >= PIPELINE_STAGES.length ? 1 : prev + 1));
    }, 2200);
    return () => window.clearInterval(timer);
  }, [autoWalk]);

  const selectManual = (step: number) => {
    setAutoWalk(false);
    setActiveStep(step);
  };

  const handlePrev = () => {
    setAutoWalk(false);
    setActiveStep((prev) => (prev <= 1 ? PIPELINE_STAGES.length : prev - 1));
  };

  const handleNext = () => {
    setAutoWalk(false);
    setActiveStep((prev) => (prev >= PIPELINE_STAGES.length ? 1 : prev + 1));
  };

  const currentStage = PIPELINE_STAGES.find((s) => s.step === activeStep) || PIPELINE_STAGES[0];
  const cumulativeMs = PIPELINE_STAGES.filter((s) => s.step <= activeStep).reduce(
    (sum, s) => sum + s.costMs,
    0
  );
  const slaPercent = Math.min(100, (cumulativeMs / 12.0) * 100);
  const progressFraction = (activeStep - 1) / (PIPELINE_STAGES.length - 1);

  return (
    <section
      id="pipeline"
      className="surface-carbon bg-[#0E0F10] text-[#F4F3EE] border-b border-[#2A2D31] arch-grid-carbon py-16 lg:py-24"
    >
      <div className="max-w-[1440px] w-full mx-auto px-6 sm:px-10 lg:px-12">
        {/* Section Header */}
        <div className="flex flex-col lg:flex-row lg:items-end justify-between gap-6 pb-8 border-b border-[#2A2D31]">
          <div>
            <div className="font-mono text-[11px] uppercase tracking-[0.16em] text-[#C8C4BA] mb-2.5">
              02 / VERIFICATION ARCHITECTURE
            </div>
            <h2 className="font-serif text-[clamp(2.3rem,4.6vw,4rem)] leading-[0.98] tracking-[-0.02em] text-[#F4F3EE]">
              Seven Gates. <em className="italic font-normal text-[#2AC78A]">One</em> Deterministic Path.
            </h2>
          </div>

          <div className="flex flex-wrap items-center gap-3 font-mono text-xs">
            <div className="flex border border-[#2A2D31] divide-x divide-[#2A2D31] bg-[#161719]">
              <button
                type="button"
                onClick={handlePrev}
                aria-label="Previous gate"
                className="px-3 py-2 text-[#F4F3EE] hover:bg-[#26282B] transition-colors inline-flex items-center gap-1"
              >
                <ChevronLeft className="w-3.5 h-3.5" />
                <span>PREV</span>
              </button>
              <span className="px-3 py-2 tabular-nums text-[#2AC78A] font-semibold">
                0{activeStep} / 0{PIPELINE_STAGES.length}
              </span>
              <button
                type="button"
                onClick={handleNext}
                aria-label="Next gate"
                className="px-3 py-2 text-[#F4F3EE] hover:bg-[#26282B] transition-colors inline-flex items-center gap-1"
              >
                <span>NEXT</span>
                <ChevronRight className="w-3.5 h-3.5" />
              </button>
            </div>

            <button
              type="button"
              onClick={() => setAutoWalk((v) => !v)}
              className={`inline-flex items-center gap-2 px-3.5 py-2 border transition-colors ${
                autoWalk
                  ? 'border-[#2AC78A] bg-[#122E24] text-[#2AC78A] font-semibold'
                  : 'border-[#3A3D42] bg-[#161719] text-[#F4F3EE] hover:border-[#F4F3EE]'
              }`}
            >
              {autoWalk ? <Pause className="w-3.5 h-3.5" /> : <Play className="w-3.5 h-3.5" />}
              <span>{autoWalk ? 'PAUSE WALK' : 'AUTO-WALK'}</span>
            </button>
          </div>
        </div>

        {/* Horizontal SVG Rail */}
        <div className="py-6 border-b border-[#2A2D31] overflow-x-auto">
          <div className="min-w-[680px] relative">
            <svg
              className="w-full h-6 overflow-visible"
              viewBox="0 0 1000 24"
              preserveAspectRatio="none"
              aria-hidden="true"
            >
              <line x1="30" y1="12" x2="970" y2="12" stroke="#2A2D31" strokeWidth="2" />
              <line
                x1="30"
                y1="12"
                x2={30 + progressFraction * 940}
                y2="12"
                stroke="#2AC78A"
                strokeWidth="2"
                className="transition-all duration-300 ease-expo"
              />
            </svg>
            <div className="grid grid-cols-7 gap-2 -mt-6 relative z-10">
              {PIPELINE_STAGES.map((stage) => {
                const isSelected = stage.step === activeStep;
                const isReached = stage.step <= activeStep;
                return (
                  <button
                    key={stage.step}
                    type="button"
                    onClick={() => selectManual(stage.step)}
                    className="flex flex-col items-center text-center group focus-visible:outline-[#F4F3EE]"
                  >
                    <span
                      className={`w-6 h-6 flex items-center justify-center font-mono text-[11px] font-semibold border transition-all duration-200 ${
                        isSelected
                          ? 'bg-[#2AC78A] text-[#0E0F10] border-[#2AC78A] scale-110'
                          : isReached
                            ? 'bg-[#161719] text-[#2AC78A] border-[#2AC78A]'
                            : 'bg-[#0E0F10] text-[#C8C4BA] border-[#3A3D42] group-hover:border-[#F4F3EE]'
                      }`}
                    >
                      0{stage.step}
                    </span>
                    <span
                      className={`mt-2 font-mono text-[10px] uppercase tracking-wider transition-colors ${
                        isSelected
                          ? 'text-[#F4F3EE] font-semibold'
                          : 'text-[#C8C4BA] group-hover:text-[#F4F3EE]'
                      }`}
                    >
                      {stage.module.replace('internal/', '')}
                    </span>
                  </button>
                );
              })}
            </div>
          </div>
        </div>

        {/* 12-Col Stage List + Stage Inspector */}
        <div className="grid grid-cols-1 lg:grid-cols-12 gap-6 pt-8 items-stretch">
          {/* Left: 7 Interactive Rows */}
          <div className="lg:col-span-6 divide-y divide-[#2A2D31] border border-[#2A2D31]">
            {PIPELINE_STAGES.map((stage) => {
              const isSelected = stage.step === activeStep;
              return (
                <button
                  key={stage.step}
                  type="button"
                  onClick={() => selectManual(stage.step)}
                  className={`w-full text-left px-5 py-4 flex items-center justify-between gap-4 transition-colors duration-200 ${
                    isSelected
                      ? 'bg-[#161719] border-l-2 border-l-[#2AC78A]'
                      : 'bg-[#0E0F10] hover:bg-[#161719]/80'
                  }`}
                >
                  <div className="flex items-start gap-4">
                    <span
                      className={`font-mono text-xs tabular-nums pt-0.5 ${
                        isSelected ? 'text-[#2AC78A] font-semibold' : 'text-[#A3A097]'
                      }`}
                    >
                      0{stage.step}
                    </span>
                    <div>
                      <div className="font-sans text-sm font-semibold text-[#F4F3EE]">
                        {stage.title}
                      </div>
                      <div className="font-mono text-[11px] text-[#C8C4BA] mt-0.5">
                        {stage.module}
                      </div>
                    </div>
                  </div>
                  <div className="font-mono text-xs tabular-nums text-[#F4F3EE] shrink-0">
                    +{stage.costMs.toFixed(2)} ms
                  </div>
                </button>
              );
            })}
          </div>

          {/* Right: Stage Inspector */}
          <div className="lg:col-span-6 border border-[#2A2D31] bg-[#161719] p-6 sm:p-7 flex flex-col justify-between gap-5">
            <div>
              <div className="flex items-center justify-between gap-4 pb-3 border-b border-[#2A2D31]">
                <span className="font-mono text-[11px] uppercase tracking-[0.14em] text-[#2AC78A] font-semibold">
                  STAGE 0{currentStage.step} / {currentStage.module}
                </span>
                <span className="font-mono text-xs tabular-nums text-[#F4F3EE]">
                  +{currentStage.costMs.toFixed(2)} ms
                </span>
              </div>

              <h3 className="font-serif text-2xl sm:text-3xl text-[#F4F3EE] mt-4 mb-2">
                {currentStage.title}
              </h3>
              <p className="font-sans text-sm text-[#E2DFD7] leading-relaxed mb-5">
                {currentStage.summary}
              </p>

              <div className="border border-[#2A2D31] bg-[#0E0F10] p-4">
                <div className="font-mono text-[10px] uppercase tracking-[0.14em] text-[#C8C4BA] mb-2">
                  {currentStage.payloadTitle}
                </div>
                <pre className="font-mono text-xs text-[#F4F3EE] overflow-x-auto leading-relaxed whitespace-pre-wrap">
                  {currentStage.payload}
                </pre>
              </div>
            </div>

            {/* Invariant & Cumulative Budget Meter */}
            <div className="space-y-4 pt-4 border-t border-[#2A2D31]">
              <div className="flex items-start gap-3 text-xs font-mono">
                <span className="px-1.5 py-0.5 bg-[#3B1614] text-[#FF6B5E] border border-[#E63B2E]/50 uppercase shrink-0 font-semibold">
                  Invariant
                </span>
                <span className="text-[#E2DFD7] leading-relaxed">{currentStage.invariant}</span>
              </div>

              <div>
                <div className="flex items-center justify-between font-mono text-[11px] mb-2">
                  <span className="text-[#C8C4BA] uppercase tracking-wider">
                    Cumulative Pipeline Budget (Step 1 &rarr; {currentStage.step})
                  </span>
                  <span className="tabular-nums font-semibold text-[#2AC78A]">
                    {cumulativeMs.toFixed(2)} ms / 12.00 ms SLA
                  </span>
                </div>
                <div className="h-2 w-full bg-[#0E0F10] border border-[#2A2D31] overflow-hidden">
                  <div
                    className="h-full bg-[#2AC78A] transition-all duration-300 ease-expo"
                    style={{ width: `${slaPercent}%` }}
                  />
                </div>
              </div>
            </div>
          </div>
        </div>
      </div>
    </section>
  );
};
